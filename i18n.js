function gpsfLocale() {
  let lang = "";
  try {
    lang = chrome.i18n.getUILanguage() || "";
  } catch {}
  if (!lang && typeof navigator !== "undefined") {
    lang = navigator.language || "";
  }
  const lower = String(lang).toLowerCase().replace(/_/g, "-");
  if (
    lower.startsWith("zh-tw") ||
    lower.startsWith("zh-hk") ||
    lower.startsWith("zh-mo") ||
    lower.includes("hant")
  ) {
    return "zh_TW";
  }
  if (lower.startsWith("zh")) return "zh_CN";
  if (lower.startsWith("ja")) return "ja";
  if (lower.startsWith("en")) return "en_US";
  return "zh_TW";
}

function gpsfMsg(key, substitutions) {
  const locale = gpsfLocale();
  const template =
    (GPSF_I18N[locale] && GPSF_I18N[locale][key]) ||
    GPSF_I18N.zh_TW[key] ||
    key;
  if (!substitutions || !substitutions.length) return template;
  return template.replace(/\$(\d+)/g, (_, n) => {
    const value = substitutions[Number(n) - 1];
    return value == null ? "" : String(value);
  });
}
